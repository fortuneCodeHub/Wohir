#!/usr/bin/python3
"""
    Email Sender — Handles email-only job applications.
    Generates subject and body via Agent 7 in application_brain.py.
    Attaches the targeted CV PDF built by cv_builder.py.
    Sends via Gmail SMTP using an app password.
    Never attaches the generic fallback resume to email applications.
    Always uses the targeted CV.
    Author: Fortune Nwohiri
"""
import os
import smtplib
import time
import random
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.mime.base import MIMEBase
from email.mime.application import MIMEApplication
from email import encoders
from pathlib import Path
from logging_config.logger import get_logger

logger = get_logger("EmailSender")


class EmailSender:
    """
    Sends job application emails via Gmail SMTP.

    Setup — add these to your .env file:
        JOB_AGENT_EMAIL=fortunenwohiri@gmail.com
        JOB_AGENT_APP_PASSWORD=your-gmail-app-password

    Gmail App Password setup:
        Google Account → Security → 2-Step Verification → App Passwords
        Generate one for Mail. Use that value, not your main password.

    Never sends the generic fallback resume.
    Always attaches the targeted CV generated by cv_builder.py.
    """

    SMTP_HOST = "smtp.gmail.com"
    SMTP_PORT = 587

    # Retry config
    MAX_RETRIES = 3
    RETRY_DELAY_MIN = 10
    RETRY_DELAY_MAX = 30

    def __init__(self):
        self.sender_email = os.environ.get("JOB_AGENT_EMAIL", "")
        self.app_password = os.environ.get("JOB_AGENT_APP_PASSWORD", "")

        if not self.sender_email:
            logger.warning(
                "JOB_AGENT_EMAIL not set in environment. "
                "Email sends will fail. Add it to your .env file."
            )
        if not self.app_password:
            logger.warning(
                "JOB_AGENT_APP_PASSWORD not set in environment. "
                "Email sends will fail. Add it to your .env file."
            )

    def _is_configured(self) -> bool:
        """Check if SMTP credentials are available."""
        return bool(self.sender_email and self.app_password)

    def _build_message(
        self,
        to_email: str,
        subject: str,
        body: str,
        resume_path: str,
        cover_letter_path: str = "",
    ) -> MIMEMultipart:
        """
        Build the full MIME email message.
        Always attaches the CV PDF.
        Optionally attaches a cover letter PDF if one was generated.

        Args:
            to_email: Recruiter email address
            subject: Email subject line
            body: Plain text email body
            resume_path: Absolute path to Fortune_Nwohiri_CV.pdf
            cover_letter_path: Optional path to cover letter PDF

        Returns:
            MIMEMultipart message object ready to send
        """
        msg = MIMEMultipart()
        msg["From"] = self.sender_email
        msg["To"] = to_email
        msg["Subject"] = subject

        # Email body — plain text
        msg.attach(MIMEText(body, "plain"))

        # Attach CV PDF
        abs_resume = str(Path(resume_path).resolve())
        if os.path.exists(abs_resume):
            with open(abs_resume, "rb") as f:
                cv_attachment = MIMEApplication(f.read(), _subtype="pdf")
            cv_attachment.add_header(
                "Content-Disposition",
                "attachment",
                filename="Fortune_Nwohiri_CV.pdf",
            )
            msg.attach(cv_attachment)
            logger.info("CV PDF attached: Fortune_Nwohiri_CV.pdf")
        else:
            logger.error(f"CV PDF not found at: {abs_resume}")

        # Attach cover letter PDF if available
        if cover_letter_path:
            abs_cl = str(Path(cover_letter_path).resolve())
            if os.path.exists(abs_cl):
                with open(abs_cl, "rb") as f:
                    cl_attachment = MIMEApplication(f.read(), _subtype="pdf")
                cl_attachment.add_header(
                    "Content-Disposition",
                    "attachment",
                    filename="Fortune_Nwohiri_Cover_Letter.pdf",
                )
                msg.attach(cl_attachment)
                logger.info("Cover letter PDF attached: Fortune_Nwohiri_Cover_Letter.pdf")
            else:
                logger.warning(f"Cover letter PDF not found at: {abs_cl}")

        return msg

    def send_application(
        self,
        to_email: str,
        subject: str,
        body: str,
        resume_path: str,
        cover_letter_path: str = "",
    ) -> bool:
        """
        Send a job application email with CV attached.

        Args:
            to_email: Recruiter or HR email address
            subject: Email subject line from Agent 7
            body: Email body from Agent 7
            resume_path: Path to Fortune_Nwohiri_CV.pdf from cv_builder.py
            cover_letter_path: Optional path to cover letter PDF

        Returns:
            bool: True if sent successfully
        """
        if not self._is_configured():
            logger.error(
                "Email not configured. "
                "Set JOB_AGENT_EMAIL and JOB_AGENT_APP_PASSWORD in .env"
            )
            return False

        if not to_email or "@" not in to_email:
            logger.error(f"Invalid recipient email: {to_email}")
            return False

        if not subject:
            logger.error("Empty subject line, cannot send")
            return False

        if not body:
            logger.error("Empty email body, cannot send")
            return False

        abs_resume = str(Path(resume_path).resolve())
        if not os.path.exists(abs_resume):
            logger.error(f"Resume PDF not found: {abs_resume}")
            return False

        msg = self._build_message(
            to_email=to_email,
            subject=subject,
            body=body,
            resume_path=resume_path,
            cover_letter_path=cover_letter_path,
        )

        # Send with retry logic
        for attempt in range(self.MAX_RETRIES):
            try:
                logger.info(
                    f"Sending email to {to_email} "
                    f"(attempt {attempt + 1}/{self.MAX_RETRIES})"
                )

                with smtplib.SMTP(self.SMTP_HOST, self.SMTP_PORT) as server:
                    server.ehlo()
                    server.starttls()
                    server.ehlo()
                    server.login(self.sender_email, self.app_password)
                    server.sendmail(
                        self.sender_email,
                        to_email,
                        msg.as_string(),
                    )

                logger.info(
                    f"Email sent successfully: '{subject}' → {to_email}"
                )
                return True

            except smtplib.SMTPAuthenticationError:
                logger.error(
                    "SMTP authentication failed. "
                    "Check JOB_AGENT_APP_PASSWORD in .env. "
                    "Make sure you are using an App Password, "
                    "not your main Gmail password."
                )
                return False

            except smtplib.SMTPRecipientsRefused as e:
                logger.error(f"Recipient refused: {to_email} — {e}")
                return False

            except smtplib.SMTPException as e:
                logger.warning(f"SMTP error on attempt {attempt + 1}: {e}")
                if attempt < self.MAX_RETRIES - 1:
                    delay = random.uniform(self.RETRY_DELAY_MIN, self.RETRY_DELAY_MAX)
                    logger.info(f"Retrying in {delay:.1f}s")
                    time.sleep(delay)
                continue

            except ConnectionRefusedError:
                logger.error(
                    "Connection to Gmail SMTP refused. "
                    "Check your internet connection."
                )
                if attempt < self.MAX_RETRIES - 1:
                    delay = random.uniform(self.RETRY_DELAY_MIN, self.RETRY_DELAY_MAX)
                    logger.info(f"Retrying in {delay:.1f}s")
                    time.sleep(delay)
                continue

            except Exception as e:
                logger.error(f"Unexpected email error on attempt {attempt + 1}: {e}")
                if attempt < self.MAX_RETRIES - 1:
                    delay = random.uniform(self.RETRY_DELAY_MIN, self.RETRY_DELAY_MAX)
                    logger.info(f"Retrying in {delay:.1f}s")
                    time.sleep(delay)
                continue

        logger.error(
            f"Email failed after {self.MAX_RETRIES} attempts: "
            f"'{subject}' → {to_email}"
        )
        return False

    def send_morning_report(
        self,
        report_path: str,
        recipient_email: str = "",
    ) -> bool:
        """
        Email the morning session report to Fortune.
        Called by report_generator.py at the end of every run.

        Args:
            report_path: Path to the markdown report file
            recipient_email: Defaults to sender email (Fortune's Gmail)

        Returns:
            bool: True if sent successfully
        """
        if not self._is_configured():
            logger.warning("Email not configured, skipping morning report email")
            return False

        to_email = recipient_email or self.sender_email
        abs_report = str(Path(report_path).resolve())

        if not os.path.exists(abs_report):
            logger.error(f"Report file not found: {abs_report}")
            return False

        with open(abs_report, "r", encoding="utf-8") as f:
            report_content = f.read()

        # Extract summary line from report for subject
        subject = "Job Agent Morning Report"
        for line in report_content.split("\n"):
            if "Applied" in line and "|" in line:
                try:
                    applied_count = line.split("|")[1].strip()
                    subject = f"Job Agent Report — {applied_count} applications"
                    break
                except Exception:
                    pass

        msg = MIMEMultipart()
        msg["From"] = self.sender_email
        msg["To"] = to_email
        msg["Subject"] = subject

        # Body is the report content as plain text
        msg.attach(MIMEText(report_content, "plain"))

        # Also attach the markdown file
        with open(abs_report, "rb") as f:
            attachment = MIMEBase("application", "octet-stream")
            attachment.set_payload(f.read())
        encoders.encode_base64(attachment)
        attachment.add_header(
            "Content-Disposition",
            f"attachment; filename={Path(abs_report).name}",
        )
        msg.attach(attachment)

        try:
            with smtplib.SMTP(self.SMTP_HOST, self.SMTP_PORT) as server:
                server.ehlo()
                server.starttls()
                server.ehlo()
                server.login(self.sender_email, self.app_password)
                server.sendmail(self.sender_email, to_email, msg.as_string())

            logger.info(f"Morning report emailed to {to_email}")
            return True

        except Exception as e:
            logger.error(f"Morning report email failed: {e}")
            return False